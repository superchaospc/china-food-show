#!/usr/bin/env python3
"""Check burned-in English captions on decoded video against source frames and a cue manifest."""
import argparse
from contextlib import ExitStack
from fractions import Fraction
import json
from pathlib import Path
import subprocess
import tempfile

import numpy as np

from captions import probe


def ffmpeg(*args, **kwargs):
    return subprocess.Popen(['ffmpeg','-nostdin','-v','error','-threads','3','-filter_threads','2',*args],
                            stdout=subprocess.PIPE, **kwargs)


def sample_templates(ass, count, canvas, filter_graph, sample_shape):
    parts = ass.read_text().split('[Events]\n', 1)
    if len(parts) != 2:
        raise ValueError('Expected ASS generated by captions.py')
    lines = parts[1].splitlines()
    rows = [s.split(',', 9) for s in lines if s.startswith('Dialogue:')]
    if len(rows) != count:
        raise ValueError('Cue count differs between English ASS and the Chinese frame intervals')
    def timestamp(t):
        return f'{t//3600}:{t//60%60:02}:{t%60:02}.00'
    for i,row in enumerate(rows):
        row[1:3] = [timestamp(i),timestamp(i+1)]
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp)/'templates.ass'
        path.write_text(parts[0]+'[Events]\n'+lines[0]+'\n'+'\n'.join(','.join(s) for s in rows)+'\n')
        def render(color):
            with ffmpeg('-f','lavfi','-i',f'color={color}:s={canvas}:r=1:d={count}',
                        '-vf','ass=templates.ass,'+filter_graph,'-f','rawvideo','-',cwd=tmp) as proc:
                raw, _ = proc.communicate()
                if proc.returncode:
                    raise RuntimeError('Could not render subtitle reference templates')
            return np.frombuffer(raw, np.uint8).reshape(count, *sample_shape).astype(np.float32)
        black, white = render('black'), render('white')
    transmission = (white-black)/255
    masks = transmission < .8
    if np.any(masks.sum(axis=(1,2)) < 8):
        raise ValueError('A cue has too few visible text pixels in the selected ROI; inspect the crop/resolution')
    return black, transmission, masks


def check(args):
    reference_pts, w, h = probe(args.reference.resolve())
    output_pts, wo, ho = probe(args.output.resolve())
    if (w,h)!=(wo,ho) or len(reference_pts)!=len(output_pts) or any(abs(a-b)>Fraction(1,1000) for a,b in zip(reference_pts,output_pts)):
        raise ValueError('Frame count, geometry, or timestamps differ between reference and output')
    rows = json.loads(args.cues.read_text())
    count = len(reference_pts)-1
    schedule = [-1]*count
    last = 0
    for i,row in enumerate(rows):
        a,b = row['start_frame'],row['end_frame_exclusive']
        if not (last<=a<b<=count):
            raise ValueError(f'Invalid Chinese interval {i+1}')
        schedule[a:b] = [i]*(b-a)
        last=b
    x,y,width,height = map(int,args.roi.split(','))
    if not (0<=x<x+width<=w and 0<=y<y+height<=h):
        raise ValueError('ROI outside the source canvas')
    sw=min(width,480); sh=max(1,round(height*sw/width))
    graph=f'crop={width}:{height}:{x}:{y},scale={sw}:{sh}:flags=area,format=gray'
    black, transmission, masks = sample_templates(args.ass, len(rows), f'{w}x{h}', graph, (sh,sw))
    failures=[]
    min_ink=int(masks.sum(axis=(1,2)).min())
    with ExitStack() as stack:
        procs=[stack.enter_context(ffmpeg('-i',str(path.resolve()),'-map','0:v:0','-vf',graph,'-fps_mode','passthrough','-f','rawvideo','-'))
               for path in (args.reference,args.output)]
        for n,c in enumerate(schedule):
            source, actual = [np.frombuffer(p.stdout.read(sw*sh),np.uint8).reshape(sh,sw).astype(np.float32) for p in procs]
            if c<0:
                if np.count_nonzero(np.abs(actual-source)>37)>max(5,min(28,min_ink//6)):
                    failures.append((n,'unexpected change on blank frame'))
                continue
            pred=black[c]+source*transmission[c]; mask=masks[c]
            error=np.abs(actual-pred)[mask].mean()
            change=np.abs(actual-source)[mask].mean()
            if error/max(1,change)>.43:
                failures.append((n,'expected English glyphs missing/different'))
            if n in (rows[c]['start_frame'],rows[c]['end_frame_exclusive']-1):
                for other in (c-1,c+1):
                    if other<0 or other>=len(rows) or rows[other]['en']==rows[c]['en']:
                        continue
                    alt=black[other]+source*transmission[other]; union=mask|masks[other]
                    if np.abs(actual-alt)[union].mean()+1<np.abs(actual-pred)[union].mean():
                        failures.append((n,'closer to adjacent cue')); break
        for p in procs:
            if p.stdout.read(1) or p.wait():
                raise RuntimeError('Unexpected decoder output length or decoder failure')
    return {'passed':not failures,'frames':count,'cues':len(rows),'blank_frames':schedule.count(-1),
            'flagged_frames':len({n for n,_ in failures}),'first_findings':failures[:40]}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('reference',type=Path,help='Picture aligned to output, without the English caption layer')
    parser.add_argument('output',type=Path,help='Finished deliverable')
    parser.add_argument('cues',type=Path)
    parser.add_argument('ass',type=Path)
    parser.add_argument('--roi',required=True,help='x,y,width,height covering all English ink, avoiding other changes')
    args=parser.parse_args()
    report=check(args)
    print(json.dumps(report,ensure_ascii=False,indent=2))
    raise SystemExit(0 if report['passed'] else 1)


if __name__=='__main__':
    main()
